    /** Канон названия: значение из словаря или само имя. */
    public static function canon(string $name): string
    {
        return self::CANON[$name] ?? $name;
    }

    /**
     * Нормализует список упражнений сессии: приводит имена к канону и склеивает
     * подходы упражнений с одинаковым каноном (порядок — по первому появлению).
     * Зеркало normSession() из src/data.js (оставляет только поля n и sets).
     *
     * @param array $exercises список вида [ ['n' => string, 'sets' => array], ... ]
     * @return array
     */
    public static function normExercises(array $exercises): array
    {
        $order = [];
        $byCanon = [];
        foreach ($exercises as $e) {
            if (!is_array($e)) continue;
            $n = self::canon((string) ($e['n'] ?? ''));
            $sets = (isset($e['sets']) && is_array($e['sets'])) ? $e['sets'] : [];
            if (!array_key_exists($n, $byCanon)) {
                $byCanon[$n] = ['n' => $n, 'sets' => []];
                $order[] = $n;
            }
            foreach ($sets as $st) {
                $byCanon[$n]['sets'][] = $st;
            }
        }
        $out = [];
        foreach ($order as $n) {
            $out[] = $byCanon[$n];
        }
        return $out;
    }
